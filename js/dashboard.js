function days(s){return s.deadlineDate?Math.ceil((new Date(s.deadlineDate+'T23:59:59')-new Date())/86400000):null;}
function animateStat(element, target) {
  const current = Number(element.textContent) || 0;

  if (current === target) {
    return;
  }

  const duration = 450;
  const start = performance.now();

  function step(now) {
    const progress = Math.min(
      (now - start) / duration,
      1
    );

    const eased =
      1 - Math.pow(1 - progress, 3);

    element.textContent =
      Math.round(current + (target - current) * eased);

    if (progress < 1) {
      requestAnimationFrame(step);
    }
  }

  element.classList.remove('stat-pop');
  void element.offsetWidth;
  element.classList.add('stat-pop');

  requestAnimationFrame(step);
}


function deadlineTone(s) {
  const d = days(s);

  if (d === null) {
    return 'deadline-unknown';
  }

  if (d <= 3) {
    return 'deadline-urgent';
  }

  if (d <= 14) {
    return 'deadline-warning';
  }

  if (d <= 45) {
    return 'deadline-soon';
  }

  return 'deadline-normal';
}


function stagePercent(s) {
  const values = {
    Interested: 20,
    Preparing: 40,
    Applied: 60,
    Interview: 80,
    Result: 100
  };

  return values[stage(s)] || 20;
}
async function loadUser(){

  if(!client){
    render();
    return;
  }

  const r = await client.auth.getUser();
  user = r.data.user;

  if(user){

    modePill.textContent = 'Account mode';

    // Load saved scholarships
    const q = await client
      .from('saved_scholarships')
      .select('scholarship_id')
      .eq('user_id', user.id);

    if(q.error){

      console.error(
        'Saved scholarships load failed:',
        q.error
      );

    } else {

      saved = new Set(
        q.data.map(x => String(x.scholarship_id))
      );

    }

    // Load application stages separately
    const stages = await client
      .from('user_scholarships')
      .select('scholarship_id, stage')
      .eq('user_id', user.id);

    if(stages.error){

      console.error(
        'Application stages load failed:',
        stages.error
      );

    } else {

      stages.data.forEach(x => {

        if(x.stage){

          localStorage.setItem(
            'sf-stage-' + x.scholarship_id,
            x.stage
          );

        }

      });

    }

  } else {

    modePill.textContent = 'Guest mode';

  }

  render();

}
